// The worklets a bundle defines, compiled ahead of time for worklets' UI runtime
// (docs/performance.mdx, "Worklets compiled ahead of time").
//
// react-native-worklets' Babel plugin gives every worklet its source text and a hash
// (`fn.__workletHash = N`, `fn.__initData = {code: "(function …)"}`), and its UI runtime makes the
// function from that text the first time the worklet runs there, with `eval`: Hermes compiling
// each from source, about a quarter of a millisecond each, hundreds of them before an
// application's first frame shows its text. This reads every worklet a bundle defines and writes
// them as one script, a table of the functions by the URL worklets evaluates each under
// (`worklet_<hash>`), which the runtime's `hermesc` compiles with the bundle; the host evaluates
// it on the UI runtime and hands worklets the compiled function (worklets-host.cpp,
// `evalWithSourceUrl`).
//
// Each function is the worklet's own text, at the top level of a script of its own: what worklets'
// `eval` of it gives (Hermes' `eval` is always global), compiled once, by the same `hermesc`.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

// The plugin's name for a worklet's source (`_worklet_<hash>_init_data`, numbered when one
// scope has two).
const INIT_DATA = /^_worklet_(\d+)_init_data\d*$/;

/** The worklets `source` (a bundle's JavaScript, not minified) defines: their source text by hash. */
export function workletsOf(source, bloom) {
  const parser = createRequire(path.join(bloom, 'package.json'))('@babel/parser');
  const program = parser.parse(source, { sourceType: 'script' }).program;
  const hashes = new Set();
  const texts = new Map();
  // A walk of the tree by hand: Babel's traverse makes a path for every node, ten times as slow
  // over a framework's 26 MB.
  const nodes = [program];
  while (nodes.length > 0) {
    const node = nodes.pop();
    if (node.type === 'AssignmentExpression' && node.left.type === 'MemberExpression' && !node.left.computed &&
        node.left.property.name === '__workletHash' && node.right.type === 'NumericLiteral') {
      hashes.add(String(node.right.value));
    } else if (node.type === 'VariableDeclarator' && node.id.type === 'Identifier' &&
               node.init?.type === 'ObjectExpression') {
      const named = INIT_DATA.exec(node.id.name);
      const code = named && node.init.properties.find((property) => property.type === 'ObjectProperty' &&
        !property.computed && property.key.type === 'Identifier' && property.key.name === 'code');
      if (code?.value.type === 'StringLiteral') texts.set(named[1], code.value.value);
    }
    for (const key in node) {
      if (key === 'loc' || key === 'leadingComments' || key === 'trailingComments' || key === 'innerComments') continue;
      const value = node[key];
      if (Array.isArray(value)) {
        for (const child of value) if (child && typeof child.type === 'string') nodes.push(child);
      } else if (value && typeof value.type === 'string') {
        nodes.push(value);
      }
    }
  }
  // Every worklet the bundle defines is in the table, or the build says why: one left to `eval`
  // would cost its compilation again at every launch, unseen.
  const missing = [...hashes].filter((hash) => !texts.has(hash));
  if (missing.length > 0) {
    throw new Error(`worklets.mjs: ${missing.length} of the bundle's ${hashes.size} worklets have no source text ` +
      `it can read (react-native-worklets' plugin changed how it writes them?): ${missing.slice(0, 5).join(', ')}`);
  }
  return new Map([...texts].filter(([hash]) => hashes.has(hash)));
}

/** The table's script for `worklets` (hash to source text). */
export function workletTable(worklets) {
  const entries = [...worklets].map(([hash, text]) => `  ${JSON.stringify(`worklet_${hash}`)}: ${text},`);
  return [
    '// Generated by worklets.mjs: every worklet of the bundle, by the URL worklets evaluates it under.',
    'globalThis.__oxyosWorklets = {',
    '  __proto__: null,',
    ...entries,
    '};',
    '',
  ].join('\n');
}

/**
 * Writes the worklets the bundle at `source` defines to `out` (bytecode, compiled by `hermesc`),
 * through a script beside it that is removed once compiled; their count.
 */
export function compileWorklets(source, out, hermesc, bloom, execFileSync) {
  const worklets = workletsOf(fs.readFileSync(source, 'utf8'), bloom);
  const script = `${out}.js`;
  fs.writeFileSync(script, workletTable(worklets));
  execFileSync(hermesc, ['-emit-binary', '-O', '-w', '-out', out, script], { stdio: 'inherit' });
  fs.rmSync(script);
  return worklets.size;
}
